/**
 * Helper to get guitar diagram data or return a fallback generated pattern.
 */
export function getGuitarChordDiagram(chordName: string): GuitarChordData {
  const clean = chordName.trim();
  if (COMMON_GUITAR_CHORDS[clean]) {
    return COMMON_GUITAR_CHORDS[clean];
  }

  // Handle slash chord fallback (e.g. C/G -> return C diagram)
  if (clean.includes('/')) {
    const main = clean.split('/')[0];
    if (COMMON_GUITAR_CHORDS[main]) {
      return { ...COMMON_GUITAR_CHORDS[main], name: clean };
    }
  }

  // Generic default diagram if not in preset table
  return {
    name: clean,
    frets: [0, 0, 0, 0, 0, 0]
  };
}
